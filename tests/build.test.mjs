/**
 * Artifact tests: index.html must be one self-contained file that cannot reach
 * the network, and must match what src/ says.
 *
 * The preview environment is an opaque-origin iframe with scripts allowed and
 * no guarantee of storage or network, so any external reference is a bug that
 * would show up as a blank page rather than an error.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ARTIFACT = join(ROOT, 'index.html');

/**
 * Rebuild index.html in this process and return its bytes.
 *
 * The builder is imported rather than spawned. A test that shells out to the
 * build cannot run in a sandbox that forbids child processes (spawning node
 * fails with EPERM), and "the artifact must be current" is a property of the
 * bytes, not of who produced them.
 */
async function rebuild() {
  const previous = existsSync(ARTIFACT) ? readFileSync(ARTIFACT) : null;
  const builder = await import(pathToFileURL(join(ROOT, 'tools', 'build-lib.mjs')).href);
  const generated = Buffer.from(builder.buildArtifact(ROOT), 'utf8');
  if (previous === null || !previous.equals(generated)) writeFileSync(ARTIFACT, generated);
  return generated;
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * The artifact as the repository holds it, read once at load time.
 *
 * It has to be captured before any test runs, because `rebuild()` writes
 * index.html: a staleness check that reads the file afterwards compares fresh
 * bytes against fresh bytes and can never fail. That is not a hypothetical - the
 * first version of this check passed while index.html was genuinely stale.
 */
const AS_COMMITTED = existsSync(ARTIFACT) ? readFileSync(ARTIFACT) : null;

test('the artifact is regenerated from src/ before anything else is asserted', async () => {
  const bytes = await rebuild();
  assert.ok(bytes.length > 10_000, `artifact looks truncated: ${bytes.length} bytes`);
});

test('the committed artifact matches what src/ produces', async () => {
  // If these differ, the repository was committed with a stale index.html and
  // every screenshot taken since then was of the wrong page.
  assert.ok(AS_COMMITTED !== null, `there is no ${ARTIFACT} to check; run node tools/build.mjs`);
  const builder = await import(pathToFileURL(join(ROOT, 'tools', 'build-lib.mjs')).href);
  const fresh = Buffer.from(builder.buildArtifact(ROOT), 'utf8');
  assert.equal(
    sha256(AS_COMMITTED),
    sha256(fresh),
    'index.html is stale: run node tools/build.mjs and commit the result',
  );
});

test('the build is deterministic', async () => {
  const builder = await import(pathToFileURL(join(ROOT, 'tools', 'build-lib.mjs')).href);
  const first = sha256(Buffer.from(builder.buildArtifact(ROOT), 'utf8'));
  const second = sha256(Buffer.from(builder.buildArtifact(ROOT), 'utf8'));
  assert.equal(first, second, 'the build is not deterministic, so goldens could not be trusted');
});

test('the artifact makes no network requests of any kind', async () => {
  const html = (await rebuild()).toString('utf8');
  const patterns = [
    ['http:// or https:// URL', /https?:\/\//i],
    ['protocol-relative URL', /["'(]\/\//],
    ['external <script src>', /<script[^>]+\bsrc\s*=/i],
    ['external <link href>', /<link[^>]+\bhref\s*=/i],
    ['@import', /@import/i],
    ['fetch(', /\bfetch\s*\(/],
    ['XMLHttpRequest', /XMLHttpRequest/],
    ['WebSocket', /WebSocket/],
    ['EventSource', /EventSource/],
    ['import(', /\bimport\s*\(/],
  ];
  for (const [label, pattern] of patterns) {
    const match = pattern.exec(html);
    assert.equal(match, null, `${label} found in the artifact: ${match && match[0]}`);
  }
});

test('the artifact uses no browser storage', async () => {
  const html = (await rebuild()).toString('utf8');
  for (const api of ['localStorage', 'sessionStorage', 'indexedDB', 'caches', 'document.cookie']) {
    assert.ok(!html.includes(api), `${api} would throw or be unavailable in a sandboxed opaque-origin frame`);
  }
});

test('the artifact is a single file with the app inlined', async () => {
  const html = (await rebuild()).toString('utf8');
  assert.match(html, /^<!-- Aurelia: generated by tools\/build\.mjs/);
  assert.match(html, /<!doctype html>/i);
  // Both placeholders must be gone, and the bundle must be an inlined script.
  assert.ok(!html.includes('__APP__'), 'the script was not inlined');
  assert.ok(!html.includes('__STYLE__'), 'the stylesheet was not inlined');
  assert.match(html, /<script type="module">/);
  assert.ok(!/^\s*(import|export)\s/m.test(html.slice(html.indexOf('<script type="module">'))), 'ESM syntax leaked into the inlined script');
});

test('the artifact contains the onboarding copy the design depends on', async () => {
  const html = (await rebuild()).toString('utf8');
  // These strings are the visible contract with the player: if a refactor drops
  // the explanation, the app still "works" but nobody knows how to use it.
  for (const phrase of ['Drag on empty space', 'Drag across a string', 'Drag a bright endpoint', 'How it works']) {
    assert.ok(html.includes(phrase), `onboarding text missing from the artifact: "${phrase}"`);
  }
});

test('the page is viewport-ready and touch-friendly as served', async () => {
  const html = (await rebuild()).toString('utf8');
  const viewport = /<meta name="viewport" content="([^"]+)"/.exec(html);
  assert.ok(viewport, 'a viewport meta is required for phone layouts');
  const content = viewport[1];
  assert.match(content, /width=device-width/);
  assert.match(content, /viewport-fit=cover/, 'safe-area insets need viewport-fit=cover');
  assert.match(content, /user-scalable=no/, 'pinch-zoom would fight the drawing gesture');
  assert.match(html, /touch-action:\s*none/, 'without touch-action:none the browser pans instead of drawing');
  assert.match(html, /env\(safe-area-inset-/, 'notches and gesture bars need inset handling');
});

test('the pinned live-preview link names a commit whose artifact is this one', () => {
  /*
   * The "Play it live" URL is pinned to a commit so it cannot drift underneath
   * the README, which trades a broken link for a maintenance obligation: the pin
   * goes stale the moment `index.html` changes. This makes the obligation
   * enforceable.
   *
   * The rule is that the pinned commit is the committed HEAD, and that HEAD
   * holds these exact bytes. `check.sh` rebuilds the artifact before this runs,
   * so an edited `src/` that has not been rebuilt-and-committed fails here too:
   * the published link can only name a commit that really carries the artifact
   * the suite just tested.
   *
   * HEAD is read from `.git/HEAD` rather than by running git, which keeps the
   * test working where spawning a child process is denied, and needs no git
   * installation to pass.
   */
  const readme = readFileSync(join(ROOT, 'README.md'), 'utf8');
  const pinned = readme.match(/rawcdn\.githack\.com\/dniku\/aurelia\/([0-9a-f]{40})\/index\.html/);
  assert.ok(pinned, 'README must carry a commit-pinned rawcdn.githack.com preview link');
  const [, commit] = pinned;

  const headRef = headRevision();
  assert.ok(
    headRef === commit,
    `README pins ${commit.slice(0, 7)} but HEAD is ${headRef.slice(0, 7)}. The published link ` +
      'should name the commit being released: replace it with `git rev-parse HEAD`.',
  );
});

/**
 * Resolve the current checkout to a commit SHA by reading `.git` directly.
 *
 * No subprocess: reading two small files works where spawning a child process is
 * denied, and does not make a test depend on git being installed. `existsSync`
 * distinguishes a repository's `.git/` directory from a worktree's `.git`
 * pointer file, which is the one case that cannot be handled by path arithmetic.
 */
function headRevision() {
  const asDir = join(ROOT, '.git');
  const git = existsSync(join(asDir, 'HEAD'))
    ? asDir
    : readFileSync(join(ROOT, '.git'), 'utf8').slice('gitdir:'.length).trim();
  const head = readFileSync(join(git, 'HEAD'), 'utf8').trim();
  const ref = /^ref:\s+(\S+)$/.exec(head);
  if (!ref) return head; // detached HEAD: the SHA is already here
  const refFile = join(git, ...ref[1].split('/'));
  if (existsSync(refFile)) return readFileSync(refFile, 'utf8').trim();
  // A shallow or packed clone keeps refs in one index instead of one file each.
  for (const line of readFileSync(join(git, 'packed-refs'), 'utf8').split('\n')) {
    const [sha, name] = line.trim().split(/\s+/);
    if (name === ref[1]) return sha;
  }
  throw new Error(`cannot resolve ${ref[1]} to a commit`);
}


test('the artifact embeds its own font rather than borrowing the host\u2019s', async () => {
  const html = (await rebuild()).toString('utf8');

  // Every face must be a data: URL. This is the property that CI broke: the
  // sheet asked for `ui-sans-serif, system-ui`, which fontconfig answered
  // differently on the CI runner than on a dev machine, so every line of text
  // moved and all 18 goldens failed on images that looked identical by eye.
  const faces = html.match(/@font-face\s*{[^}]*}/g) ?? [];
  assert.equal(faces.length, 2, 'expected an embedded regular and bold face');
  for (const face of faces) {
    const src = /src:\s*url\(([^)]*)\)/.exec(face);
    assert.ok(src, `an @font-face rule has no src: ${face.slice(0, 60)}`);
    assert.match(
      src[1],
      /^data:font\/woff2;base64,[A-Za-z0-9+/]{500,}={0,2}$/,
      'faces must be inline base64 WOFF2, not a reference to a file or a URL',
    );
  }

  // Both weights must exist. The sheet asks for 550-700, and without a real
  // bold face the browser synthesises one whose stem weight varies by engine,
  // which reintroduces exactly the cross-machine drift embedding removed.
  const weights = faces.map((face) => Number(/font-weight:\s*(\d+)/.exec(face)[1]));
  assert.deepEqual(weights.sort((a, b) => a - b), [400, 700]);

  // The stylesheet must actually select the embedded family, and must not fall
  // back to a system stack that would be used the moment the face is rejected.
  const bodyFamily = /\n\s*font-family:\s*([^;]*);/.exec(html);
  assert.ok(bodyFamily, 'no font-family declaration found');
  assert.match(bodyFamily[1], /^"Aurelia Sans"/);

  // The canvas sets its own font string, separately from CSS. If the two ever
  // disagree the panels and the canvas render in different faces, and only a
  // screenshot would show it.
  const app = readFileSync(join(ROOT, 'src', 'app.js'), 'utf8');
  const stack = /const FONT_STACK = '([^']*)';/.exec(app);
  assert.ok(stack, 'src/app.js must define FONT_STACK for canvas text');
  assert.match(stack[1], /^"Aurelia Sans"/, 'canvas and CSS must name the same family');
  assert.equal(
    (html.match(/Aurelia Sans/g) ?? []).length >= 4,
    true,
    'the embedded family should appear in the faces, the stylesheet and the bundle',
  );
});

test('every control is large enough for a finger', () => {
  const css = readFileSync(join(ROOT, 'src', 'styles.css'), 'utf8');
  // Every interactive control, not just the two buttons: the About disclosure is
  // a touch target too, and reading only `#controls button` is what let it ship
  // at 24px while this test was green.
  const selectors = ['#controls button', '#about summary'];
  for (const selector of selectors) {
    const block = new RegExp(`${selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*{([^}]*)}`).exec(css);
    assert.ok(block, `the styling for ${selector} should be findable by this test`);
    const rules = block[1];
    const minHeight = Number(/min-height:\s*(\d+)px/.exec(rules)[1]);
    assert.ok(minHeight >= 44, `${selector} must be at least 44px tall, got ${minHeight}px`);
  }
  const buttons = /#controls button\s*{([^}]*)}/.exec(css)[1];
  const minWidth = Number(/min-width:\s*(\d+)px/.exec(buttons)[1]);
  assert.ok(minWidth >= 44, `touch targets must be at least 44px wide, got ${minWidth}px`);
});
